import pandas as pd
import requests
import plotly.express as px
import streamlit as st

st.set_page_config(page_title="Live Earthquake Dashboard", layout="wide")

FEEDS = {
    "Past hour": "all_hour",
    "Past day": "all_day",
    "Past 7 days": "all_week",
    "Past 30 days": "all_month",
}
BASE = "https://earthquake.usgs.gov/earthquakes/feed/v1.0/summary/{}.geojson"


# ------------------------------------------------------------
# DATA LOADING (cached for 60 seconds, the feed updates every minute)
# ------------------------------------------------------------
@st.cache_data(ttl=60)
def load_data(feed_name):
    r = requests.get(BASE.format(feed_name), timeout=30)
    r.raise_for_status()
    df = pd.json_normalize(r.json()["features"])

    df["time"] = pd.to_datetime(df["properties.time"], unit="ms")
    df["lon"] = df["geometry.coordinates"].str[0]
    df["lat"] = df["geometry.coordinates"].str[1]
    df["depth_km"] = df["geometry.coordinates"].str[2]
    df = df.rename(columns={"properties.mag": "magnitude",
                            "properties.place": "place"})
    df = df[["time", "place", "magnitude", "depth_km", "lat", "lon"]]
    df = df.dropna()
    df = df[df["magnitude"] >= 0]
    df["region"] = df["place"].str.split(", ").str[-1]
    return df


# ------------------------------------------------------------
# SIDEBAR
# ------------------------------------------------------------
st.sidebar.header("Filters")
period = st.sidebar.selectbox("Time period", list(FEEDS.keys()), index=2)

if st.sidebar.button("Refresh data now"):
    st.cache_data.clear()

# Optional auto refresh (needs: pip install streamlit-autorefresh)
auto = st.sidebar.checkbox("Auto-refresh every 60 seconds")
if auto:
    try:
        from streamlit_autorefresh import st_autorefresh
        st_autorefresh(interval=60_000, key="auto")
    except ImportError:
        st.sidebar.warning("Run: pip install streamlit-autorefresh")

try:
    df = load_data(FEEDS[period])
except Exception as e:
    st.error(f"Could not load data: {e}")
    st.stop()

min_mag, max_mag = float(df["magnitude"].min()), float(df["magnitude"].max())
mag_range = st.sidebar.slider("Magnitude range", min_mag, max_mag,
                              (min_mag, max_mag))
max_depth = float(df["depth_km"].max())
depth_range = st.sidebar.slider("Depth (km)", 0.0, max_depth, (0.0, max_depth))

filtered = df[
    df["magnitude"].between(*mag_range)
    & df["depth_km"].between(*depth_range)
]

# ------------------------------------------------------------
# HEADER AND KPIs
# ------------------------------------------------------------
st.title("Live Global Earthquake Dashboard")
st.caption("Source: USGS Earthquake Hazards Program. "
           f"Last loaded: {pd.Timestamp.utcnow():%Y-%m-%d %H:%M:%S} UTC")

if filtered.empty:
    st.warning("No earthquakes match the current filters.")
    st.stop()

strongest = filtered.loc[filtered["magnitude"].idxmax()]
c1, c2, c3, c4 = st.columns(4)
c1.metric("Total earthquakes", f"{len(filtered):,}")
c2.metric("Average magnitude", f"{filtered['magnitude'].mean():.2f}")
c3.metric("Strongest", f"{strongest['magnitude']:.1f}")
c4.metric("Average depth (km)", f"{filtered['depth_km'].mean():.1f}")
st.write(f"Strongest event: **{strongest['place']}**")

# ------------------------------------------------------------
# MAP
# ------------------------------------------------------------
st.subheader("Where are earthquakes happening?")
fig_map = px.scatter_geo(
    filtered, lat="lat", lon="lon",
    size=filtered["magnitude"].clip(lower=0.1),
    color="depth_km", hover_name="place",
    hover_data={"magnitude": True, "lat": False, "lon": False},
    color_continuous_scale="Viridis_r",
    projection="natural earth",
)
fig_map.update_layout(height=500, margin=dict(l=0, r=0, t=0, b=0))
st.plotly_chart(fig_map, use_container_width=True)

# ------------------------------------------------------------
# CHARTS
# ------------------------------------------------------------
left, right = st.columns(2)

with left:
    st.subheader("Magnitude distribution")
    fig_hist = px.histogram(filtered, x="magnitude", nbins=40)
    st.plotly_chart(fig_hist, use_container_width=True)

    st.subheader("Top 10 regions")
    top = filtered["region"].value_counts().head(10).reset_index()
    top.columns = ["region", "count"]
    fig_bar = px.bar(top, x="count", y="region", orientation="h")
    fig_bar.update_layout(yaxis={"categoryorder": "total ascending"})
    st.plotly_chart(fig_bar, use_container_width=True)

with right:
    st.subheader("Earthquakes over time")
    freq = "h" if period in ("Past day", "Past 7 days") else "D"
    if period == "Past hour":
        freq = "5min"
    over_time = (filtered.set_index("time").resample(freq)
                 .size().reset_index(name="count"))
    fig_line = px.line(over_time, x="time", y="count")
    st.plotly_chart(fig_line, use_container_width=True)

    st.subheader("Depth vs magnitude")
    fig_sc = px.scatter(filtered, x="depth_km", y="magnitude", opacity=0.4)
    st.plotly_chart(fig_sc, use_container_width=True)

# ------------------------------------------------------------
# DATA TABLE AND DOWNLOAD
# ------------------------------------------------------------
st.subheader("Data table")
st.dataframe(filtered.sort_values("time", ascending=False),
             use_container_width=True, height=300)

st.download_button("Download filtered data (CSV)",
                   filtered.to_csv(index=False).encode("utf-8"),
                   file_name="earthquakes_filtered.csv",
                   mime="text/csv")

